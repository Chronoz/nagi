def used_icons():
    names = set(json.loads(r(T/'icons.json')))
    used = set()
    for p in S.rglob('*'):
        if not p.is_file() or p.suffix not in ('.js','.css','.html'): continue
        if 'vendor' in p.parts: continue
        txt = p.read_text(encoding='utf-8', errors='ignore')
        for m in re.findall(r'["\']([a-z0-9-]+)["\']', txt):
            if m in names: used.add(m)
        for m in re.findall(r'(?:ni-|--ni-)([a-z0-9-]+)', txt):
            if m in names: used.add(m)
    used |= ICON_FALLBACK
    # keep a stable order (used first by appearance in the original file, then alpha)
    return [n for n in json.loads(r(T/'icons.json')) if n in used]

def icons_css(names):
    out = json.loads(r(T/'icons.json'))
    def svg(n, sw=1.5):
        return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
                f'stroke="black" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round">{out[n]}</svg>')
    css = ['/* Icons: Lucide v1.72.0 (ISC License, (c) Lucide Contributors), stroke 1.5. Subset by src/build.py */', ':root{']
    for n in names:
        css.append(f'--ni-{n}:url("data:image/svg+xml,{quote(svg(n))}");')
    css.append('}')
    css.append('.ni{display:inline-block;width:1.15em;height:1.15em;flex:none;vertical-align:-.2em;background:currentColor;-webkit-mask:var(--ni) center/contain no-repeat;mask:var(--ni) center/contain no-repeat}')
    for n in names:
        css.append(f'.ni-{n}{{--ni:var(--ni-{n})}}')
    return '\n'.join(css)

def file_hash(path: pathlib.Path, n=10):
    return hashlib.sha256(path.read_bytes()).hexdigest()[:n]

def qurl(path, h):
    return f'{path}?nagi={h}&cache=31536000'

def subset_fonts():
    """Shrink variable fonts to Latin + Vietnamese + punctuation. Keep wght/opsz axes and common features (incl. tnum)."""
    un = 'U+0000-00FF,U+0100-017F,U+0180-024F,U+02B0-02FF,U+0300-036F,U+1E00-1EFF,U+2000-206F,U+2070-209F,U+20A0-20CF,U+2100-214F,U+2150-218F,U+2190-21FF,U+2200-22FF,U+25A0-25FF,U+6C5A'
    feats = 'kern,liga,calt,ccmp,locl,mark,mkmk,rlig,tnum,lnum,pnum,onum,frac,ordn,case,dnom,numr'
    src_dir = pathlib.Path('/tmp/v3l-theme/fonts')
    if not src_dir.exists():
        src_dir = O / 'fonts'
        # if already subset, skip
    dest = O / 'fonts'
    dest.mkdir(exist_ok=True)
    pyft = shutil.which('pyftsubset')
    if not pyft:
        return
    for name in ('inter.woff2','newsreader.woff2','newsreader-italic.woff2','plexmono.woff2'):
        src = src_dir / name
        if not src.exists():
            src = dest / name
        if not src.exists():
            continue
        tmp = pathlib.Path('/tmp') / ('nagi-' + name)
        cmd = [pyft, str(src), f'--unicodes={un}', f'--layout-features={feats}',
               '--flavor=woff2', f'--output-file={tmp}']
        try:
            subprocess.check_call(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            if tmp.exists() and tmp.stat().st_size < src.stat().st_size * 0.98:
                shutil.copy(tmp, dest / name)
            elif tmp.exists() and src.resolve() != (dest / name).resolve():
                # already small; keep smaller
                if tmp.stat().st_size < (dest / name).stat().st_size:
                    shutil.copy(tmp, dest / name)
        except subprocess.CalledProcessError:
            pass

def fonts_css():
    subset_fonts()
    lines = []
    faces = [
        ('Inter', 'inter.woff2', '100 900', None),
        ('Newsreader', 'newsreader.woff2', '200 800', None),
        ('Newsreader', 'newsreader-italic.woff2', '200 800', 'italic'),
        ('"IBM Plex Mono"', 'plexmono.woff2', '400', None),
    ]
    for fam, fn, wt, style in faces:
        h = file_hash(O/'fonts'/fn) if (O/'fonts'/fn).exists() else '0'
        url = qurl('/.nagi/fonts/' + fn, h)
        extra = f';font-style:{style}' if style else ''
        lines.append(f'@font-face{{font-family:{fam};src:url({url}) format("woff2");font-weight:{wt}{extra};font-display:swap}}')
    return '\n'.join(lines)

def minify_js(src: str) -> str:
    terser = shutil.which('terser')
    if not terser:
        return src
    p = subprocess.run(
        [terser, '--compress', 'passes=2,pure_getters,unsafe_arrows=false', '--mangle', '--comments', 'false'],
        input=src.encode(), stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if p.returncode != 0:
        sys.stderr.write(p.stderr.decode()[:2000])
        return src
    out = p.stdout.decode()
    return out if out.strip() else src

def minify_css(src: str) -> str:
    try:
        import rcssmin
        return rcssmin.cssmin(src, keep_bang_comments=False)
    except Exception:
        src = re.sub(r'/\*[^*]*\*+(?:[^/*][^*]*\*+)*/', '', src)
        src = re.sub(r'\s+', ' ', src)
        src = re.sub(r'\s*([{};:,>~+])\s*', r'\1', src)
        return src.strip()

def bake_pwa(js: str, manifest_h: str, icon_h: str) -> str:
    js = js.replace(
        "tag('link','rel','manifest',{href:B+'manifest.json'})",
        f"tag('link','rel','manifest',{{href:B+'{qurl('manifest.json', manifest_h).split('/.nagi/')[-1] if False else ''}manifest.json?nagi={manifest_h}&cache=31536000'}})")
    js = js.replace(
        "tag('link','rel','apple-touch-icon',{href:B+'icon-180.png'})",
        f"tag('link','rel','apple-touch-icon',{{href:B+'icon-180.png?nagi={icon_h}&cache=31536000'}})")
    return js

def update_manifest():
    man = O / 'manifest.json'
    if not man.exists():
        return '0'
    data = json.loads(man.read_text())
    changed = False
    for key in ('icons', 'screenshots'):
        for ic in data.get(key) or []:
            src = ic.get('src', '')
            if src.startswith('/.nagi/') or src.startswith('icon-'):
                fn = src.split('?')[0].split('/')[-1]
                fp = O / fn
                if fp.exists():
                    ic['src'] = qurl('/.nagi/' + fn, file_hash(fp))
                    changed = True
    if changed:
        man.write_text(json.dumps(data, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    return file_hash(man)

def write_run_local(hashes: dict):
    def verb(name):
        return qurl(f'/.nagi/{name}', hashes[name])
    sh = O / 'run-local.sh'
    t = sh.read_text() if sh.exists() else ''
    # css-browser, js-browser, js-other
    # quote the URLs: an unquoted & in ?nagi=&cache= is a bash background job
    t = re.sub(r"--css-browser '?\S+'?", "--css-browser '" + verb('nagi.css') + "'", t)
    t = re.sub(r"--js-browser '?\S+'?", "--js-browser '" + verb('nagi.js') + "'", t)
    t = re.sub(r"--js-other '?\S+'?", "--js-other '" + verb('nagi-pages.js') + "'", t)
    # html-head-s urls
    t = re.sub(r'href="/\.nagi/nagi-pages\.css[^"]*"', f'href="{verb("nagi-pages.css")}"', t)
    t = re.sub(r'href="/\.nagi/manifest\.json[^"]*"', f'href="{qurl("/.nagi/manifest.json", hashes["manifest.json"])}"', t)
    t = re.sub(r'href="/\.nagi/icon-180\.png[^"]*"', f'href="{qurl("/.nagi/icon-180.png", hashes["icon-180.png"])}"', t)
    if '--u2j' not in t:
        t=t.replace(' --favico', ' --u2j 4 --favico')
    if sh.exists():
        sh.write_text(t)
    (O / 'hashes.json').write_text(__import__('json').dumps(hashes, indent=2) + '\n')
    # examples/run-local.sh and examples/copyparty.conf (quoted URLs; --u2j 4)
    ex = R / 'examples' / 'run-local.sh'
    if ex.exists():
        et = ex.read_text()
        et = re.sub(r"--css-browser '?\S+'?", "--css-browser '" + verb('nagi.css') + "'", et)
        et = re.sub(r"--js-browser '?\S+'?", "--js-browser '" + verb('nagi.js') + "'", et)
        et = re.sub(r"--js-other '?\S+'?", "--js-other '" + verb('nagi-pages.js') + "'", et)
        et = re.sub(r'href="/\.nagi/nagi-pages\.css[^"]*"', 'href="' + verb('nagi-pages.css') + '"', et)
        et = re.sub(r'href="/\.nagi/manifest\.json[^"]*"', 'href="' + qurl('/.nagi/manifest.json', hashes['manifest.json']) + '"', et)
        et = re.sub(r'href="/\.nagi/icon-180\.png[^"]*"', 'href="' + qurl('/.nagi/icon-180.png', hashes['icon-180.png']) + '"', et)
        if '--u2j' not in et:
            et = et.replace(' --favico', ' --u2j 4 --favico')
        ex.write_text(et)
    cf = R / 'examples' / 'copyparty.conf'
    if cf.exists():
        ct = cf.read_text()
        def cset(key, name, path=None):
            nonlocal ct
            url = qurl(path or ('/.nagi/' + name), hashes[name])
            ct = re.sub(r'(?m)^(\s*'+key+r':\s*)\S+', r'\g<1>'+url, ct)
        cset('css-browser','nagi.css')
        cset('js-browser','nagi.js')
        cset('js-other','nagi-pages.js')
        # html-head-s is a long line
        ct = re.sub(r'href="/\.nagi/nagi-pages\.css[^"]*"', 'href="' + verb('nagi-pages.css') + '"', ct)
        ct = re.sub(r'href="/\.nagi/manifest\.json[^"]*"', 'href="' + qurl('/.nagi/manifest.json', hashes['manifest.json']) + '"', ct)
        ct = re.sub(r'href="/\.nagi/icon-180\.png[^"]*"', 'href="' + qurl('/.nagi/icon-180.png', hashes['icon-180.png']) + '"', ct)
        if 'u2j:' not in ct:
            ct = ct.replace('  # Nagi', '  u2j: 4                    # parallel upload chunks (good over Tailscale)\n  # Nagi')
        cf.write_text(ct)
    # also write a small hashes file (no secrets) for README / operators
    (O / 'hashes.json').write_text(json.dumps(hashes, indent=2) + '\n')

def build():
    names = used_icons()
    icss = icons_css(names)
    fcss = fonts_css()
    pages_base = r(T/'pages-base.css')
    pwa_css = r(S/'pwa.css')
    # shared base lives only in nagi-pages.css (loaded on every page via --html-head-s)
    # nagi.css is the app+classic layer and must come after it
    man_h = update_manifest()
    icon_h = file_hash(O/'icon-180.png') if (O/'icon-180.png').exists() else '0'
    pwa_js = bake_pwa(r(S/'pwa.js'), man_h, icon_h)

    pages_css = hdr + minify_css(fcss + '\n' + icss + '\n' + pages_base + '\n' + pwa_css)
    app_css = minify_css(r(S/'classic.css') + '\n' + r(S/'app.css') + '\n' + r(S/'bridge.css'))
    nagi_css = hdr + app_css

    nagi_js = hdr + minify_js(pwa_js + '\n' + r(S/'garden.js') + '\n' + r(S/'koi.js') + '\n' + r(S/'app.js') + '\n' + r(S/'classic.js') + '\n' + r(S/'adapter-cpp.js'))
    pages_js = hdr + minify_js(pwa_js + '\n' + r(S/'garden.js') + '\n' + r(S/'pages.js'))

    (O/'nagi.css').write_text(nagi_css)
    (O/'nagi.js').write_text(nagi_js)
    (O/'nagi-pages.css').write_text(pages_css)
    (O/'nagi-pages.js').write_text(pages_js)

    hashes = {n: file_hash(O/n) for n in ('nagi.css','nagi.js','nagi-pages.css','nagi-pages.js','manifest.json','icon-180.png')}
    write_run_local(hashes)

    # mockup (keep readable-enough; minify css/js to keep the file smaller)
    fonts = fcss.replace('/.nagi/fonts/', '../theme/fonts/')
    css = minify_css(fonts + icss + pages_base + r(S/'app.css') + r(S/'pwa.css'))
    js = minify_js(r(S/'garden.js') + '\n' + r(S/'koi.js') + '\n' + r(S/'app.js') + '\n' + r(S/'adapter-mock.js'))
    D.mkdir(exist_ok=True)
    (D/'index.html').write_text(
        '<!doctype html><html lang="en" id="ht_brw" class="fy f y nagi mock"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,initial-scale=1"><title>Nagi 凪 · demo</title>'
        '<link rel="icon" href="data:image/svg+xml,'+'%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 viewBox=%220 0 64 64%22%3E%3Ccircle cx=%2232%22 cy=%2232%22 r=%2230%22 fill=%22%2317282B%22/%3E%3Ctext x=%2232%22 y=%2243%22 font-size=%2232%22 text-anchor=%22middle%22 fill=%22%23EEE5D1%22%3E%E5%87%AA%3C/text%3E%3C/svg%3E">'
        '<style>'+css+'\nhtml,body{margin:0;height:100%;overflow:hidden;background:var(--n-paper)}</style></head><body>'
        '<script>'+js+'\nNagiApp.start(NagiMock);</script></body></html>')
    lg = r(S/'login-mock.html')
    (D/'login.html').write_text(lg.replace('/*CSS*/', minify_css(fonts + icss + pages_base)).replace('/*JS*/', minify_js(r(S/'garden.js')+'\n'+r(S/'pages.js'))))

    sizes = {p.name: p.stat().st_size for p in list(O.glob('nagi*')) + list((O/'fonts').glob('*.woff2'))}
    print('built', sizes, 'icons', len(names), 'hashes', hashes)

if __name__ == '__main__':
    build()
