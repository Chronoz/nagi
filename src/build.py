#!/usr/bin/env python3
"""Build the Nagi theme for copyparty.

  python3 src/build.py

writes theme/nagi.css, theme/nagi.js, theme/nagi-pages.css, theme/nagi-pages.js
and the offline demo in demo/ (fictional data, same app code, no server needed).
"""
import pathlib
S = pathlib.Path(__file__).resolve().parent
V = S / 'vendor'
R = S.parent
O = R / 'theme'
D = R / 'demo'
r = lambda p: p.read_text(encoding='utf-8')
hdr = ('/* Nagi 凪, a calm theme for copyparty. https://github.com/Chronoz/nagi (MIT)\n'
       '   Icons: Lucide (ISC). Fonts: Inter, Newsreader, IBM Plex Mono (SIL OFL 1.1).\n'
       '   Koi pond adapted from Mia-lab\'s "Koi Pond, Noon", used with thanks (see src/koi.js).\n'
       '   Generated by src/build.py, edit the files in src/ instead. */\n')
base = r(V / 'fonts.css') + '\n' + r(V / 'icons.css') + '\n' + r(V / 'pages-base.css')
w = lambda p, s: p.write_text(s, encoding='utf-8')
w(O / 'nagi.css', hdr + base + '\n' + r(S / 'classic.css') + '\n' + r(S / 'app.css') + '\n' + r(S / 'bridge.css') + '\n' + r(S / 'pwa.css'))
w(O / 'nagi.js', hdr + r(S / 'pwa.js') + '\n' + r(S / 'garden.js') + '\n' + r(S / 'koi.js') + '\n' + r(S / 'app.js') + '\n' + r(S / 'classic.js') + '\n' + r(S / 'adapter-cpp.js'))
w(O / 'nagi-pages.css', hdr + base + '\n' + r(S / 'pwa.css'))
w(O / 'nagi-pages.js', hdr + r(S / 'pwa.js') + '\n' + r(S / 'garden.js') + '\n' + r(S / 'pages.js'))
# offline demo
D.mkdir(exist_ok=True)
fonts = r(V / 'fonts.css').replace('/.nagi/fonts/', '../theme/fonts/')
css = fonts + r(V / 'icons.css') + r(V / 'pages-base.css') + r(S / 'app.css') + r(S / 'pwa.css')
js = r(S / 'garden.js') + '\n' + r(S / 'koi.js') + '\n' + r(S / 'app.js') + '\n' + r(S / 'adapter-mock.js')
w(D / 'index.html', '<!doctype html><html lang="en" id="ht_brw" class="fy f y nagi mock"><head><meta charset="utf-8">'
  '<meta name="viewport" content="width=device-width,initial-scale=1"><title>Nagi 凪 · demo</title>'
  '<style>' + css + '\nhtml,body{margin:0;height:100%;overflow:hidden;background:var(--n-paper)}</style></head><body>'
  '<script>' + js + '\nNagiApp.start(NagiMock);</script></body></html>')
lg = r(S / 'login-mock.html')
w(D / 'login.html', lg.replace('/*CSS*/', fonts + r(V / 'icons.css') + r(V / 'pages-base.css')).replace('/*JS*/', r(S / 'garden.js') + '\n' + r(S / 'pages.js')))
print('built', sorted(p.name for p in O.glob('nagi*')), '+ demo/')
